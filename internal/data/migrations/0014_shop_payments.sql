-- Ticket 07 (shop): payments, payment notifications and order access tokens.
-- Idempotent: every statement can run again on a migrated database.

CREATE TABLE IF NOT EXISTS payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    provider VARCHAR(40) NOT NULL,
    method VARCHAR(40) NOT NULL DEFAULT '',
    merchant_trade_no VARCHAR(20) NOT NULL,
    amount BIGINT NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'TWD',
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    provider_trade_no VARCHAR(80) NOT NULL DEFAULT '',
    masked_info JSONB,
    paid_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT payments_order_id_fkey FOREIGN KEY (order_id)
        REFERENCES orders(id) ON DELETE CASCADE,
    CONSTRAINT payments_merchant_trade_no_check CHECK (merchant_trade_no ~ '^[A-Za-z0-9]{1,20}$'),
    CONSTRAINT payments_amount_check CHECK (amount >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_payments_merchant_trade_no ON payments(merchant_trade_no);
CREATE INDEX IF NOT EXISTS idx_payments_order_id ON payments(order_id);

CREATE TABLE IF NOT EXISTS payment_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR(40) NOT NULL,
    dedupe_key VARCHAR(200) NOT NULL,
    verified BOOLEAN NOT NULL DEFAULT FALSE,
    payload JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- A notification is applied once: the same provider and dedupe key is recorded only once.
CREATE UNIQUE INDEX IF NOT EXISTS idx_payment_events_provider_dedupe ON payment_events(provider, dedupe_key);

CREATE TABLE IF NOT EXISTS order_access_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    token_hash CHAR(64) NOT NULL,
    kind VARCHAR(16) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    created_ip_masked VARCHAR(64) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT order_access_tokens_order_id_fkey FOREIGN KEY (order_id)
        REFERENCES orders(id) ON DELETE CASCADE,
    CONSTRAINT order_access_tokens_kind_check CHECK (kind IN ('lookup', 'view'))
);

-- Only the SHA-256 of a token is stored.
CREATE UNIQUE INDEX IF NOT EXISTS idx_order_access_tokens_token_hash ON order_access_tokens(token_hash);
CREATE INDEX IF NOT EXISTS idx_order_access_tokens_order_id ON order_access_tokens(order_id);
