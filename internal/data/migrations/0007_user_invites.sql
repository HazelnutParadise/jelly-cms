-- Invitations, password resets and email confirmations, all single-use
-- (docs/tickets/06-accounts.md, 資料表 user_invites). Only token hashes are stored.

CREATE TABLE IF NOT EXISTS user_invites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind VARCHAR(16) NOT NULL,
    token_hash CHAR(64) NOT NULL,
    role VARCHAR(32) NOT NULL DEFAULT '',
    note TEXT NOT NULL DEFAULT '',
    invited_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    accepted_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT user_invites_kind_check CHECK (kind IN ('invite', 'reset', 'email'))
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_user_invites_token_hash ON user_invites(token_hash);
-- Each user holds at most one live row per kind.
CREATE UNIQUE INDEX IF NOT EXISTS idx_user_invites_live_kind
    ON user_invites(user_id, kind) WHERE accepted_at IS NULL AND revoked_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_user_invites_invited_by ON user_invites(invited_by);
