CREATE TABLE IF NOT EXISTS redirects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_path VARCHAR(512) NOT NULL CHECK (char_length(from_path) > 0),
    to_url VARCHAR(2048) NOT NULL DEFAULT '',
    kind SMALLINT NOT NULL DEFAULT 301 CHECK (kind IN (301, 302, 410)),
    is_rule BOOLEAN NOT NULL DEFAULT FALSE,
    keep_query BOOLEAN NOT NULL DEFAULT FALSE,
    source VARCHAR(16) NOT NULL DEFAULT 'manual' CHECK (source IN ('manual', 'auto', 'import')),
    expires_at TIMESTAMPTZ,
    hits BIGINT NOT NULL DEFAULT 0 CHECK (hits >= 0),
    last_hit_at TIMESTAMPTZ,
    target_status SMALLINT,
    checked_at TIMESTAMPTZ,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_redirects_from_path_lower
    ON redirects (lower(from_path)) WHERE NOT is_rule;

CREATE TABLE IF NOT EXISTS not_found_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    path VARCHAR(512) NOT NULL CHECK (char_length(path) <= 512 AND position('?' IN path) = 0),
    path_hash VARCHAR(64) NOT NULL,
    count BIGINT NOT NULL DEFAULT 1 CHECK (count >= 0),
    first_seen TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen TIMESTAMPTZ NOT NULL DEFAULT now(),
    referrer_kind VARCHAR(16) NOT NULL DEFAULT 'none',
    ua_kind VARCHAR(16) NOT NULL DEFAULT 'other',
    ignored BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT not_found_log_path_hash_key UNIQUE (path_hash)
);

CREATE INDEX IF NOT EXISTS idx_not_found_log_last_seen ON not_found_log (last_seen DESC);
