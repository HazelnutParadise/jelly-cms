-- Ticket 07 (shop): server-side carts identified by a random token (only its SHA-256 is stored).
-- Idempotent: every statement can run again on a migrated database.

CREATE TABLE IF NOT EXISTS carts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash CHAR(64) NOT NULL,
    user_id BIGINT,
    coupon_code VARCHAR(64) NOT NULL DEFAULT '',
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT carts_user_id_fkey FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE SET NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_carts_token_hash ON carts(token_hash);
CREATE INDEX IF NOT EXISTS idx_carts_expires_at ON carts(expires_at);

CREATE TABLE IF NOT EXISTS cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id BIGINT NOT NULL,
    variant_id BIGINT NOT NULL,
    qty INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT cart_items_cart_id_fkey FOREIGN KEY (cart_id)
        REFERENCES carts(id) ON DELETE CASCADE,
    CONSTRAINT cart_items_variant_id_fkey FOREIGN KEY (variant_id)
        REFERENCES product_variants(id) ON DELETE CASCADE,
    CONSTRAINT cart_items_qty_check CHECK (qty BETWEEN 1 AND 99)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_cart_items_cart_variant ON cart_items(cart_id, variant_id);
