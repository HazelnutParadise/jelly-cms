-- Ticket 07 (shop): product categories, product columns, variants and stock.
-- Idempotent: every statement can run again on a migrated database.
-- Runs after GORM AutoMigrate, so the products and users tables exist.

CREATE TABLE IF NOT EXISTS product_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id BIGINT,
    name VARCHAR(120) NOT NULL DEFAULT '',
    slug VARCHAR(160) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    cover TEXT NOT NULL DEFAULT '',
    position INTEGER NOT NULL DEFAULT 0,
    hidden BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT product_categories_parent_id_fkey FOREIGN KEY (parent_id)
        REFERENCES product_categories(id) ON DELETE SET NULL,
    CONSTRAINT product_categories_slug_key UNIQUE (slug)
);

CREATE INDEX IF NOT EXISTS idx_product_categories_parent_id ON product_categories(parent_id);

CREATE TABLE IF NOT EXISTS product_category_links (
    product_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    PRIMARY KEY (product_id, category_id),
    CONSTRAINT product_category_links_product_id_fkey FOREIGN KEY (product_id)
        REFERENCES products(id) ON DELETE CASCADE,
    CONSTRAINT product_category_links_category_id_fkey FOREIGN KEY (category_id)
        REFERENCES product_categories(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_product_category_links_category_id ON product_category_links(category_id);

