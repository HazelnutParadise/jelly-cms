CREATE TABLE IF NOT EXISTS product_variants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    name VARCHAR(120) NOT NULL DEFAULT '',
    sku VARCHAR(100) NOT NULL DEFAULT '',
    price BIGINT NOT NULL DEFAULT 0,
    compare_at_price BIGINT NOT NULL DEFAULT 0,
    stock INTEGER NOT NULL DEFAULT 0,
    position INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(16) NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT product_variants_product_id_fkey FOREIGN KEY (product_id)
        REFERENCES products(id) ON DELETE CASCADE,
    CONSTRAINT product_variants_stock_check CHECK (stock >= 0),
    CONSTRAINT product_variants_price_check CHECK (price >= 0 AND compare_at_price >= 0)
);

CREATE INDEX IF NOT EXISTS idx_product_variants_product_id ON product_variants(product_id);

-- Every product gets one default variant (empty name). Only products without any variant are touched,
-- so rerunning the migration never adds a second default variant.
INSERT INTO product_variants (product_id, name, sku, price, compare_at_price, stock, position, status, created_at, updated_at)
SELECT p.id,
       '',
       COALESCE(p.sku, ''),
       GREATEST(COALESCE(p.price, 0), 0),
       GREATEST(COALESCE(p.compare_at_price, 0), 0),
       GREATEST(COALESCE(p.stock, 0), 0),
       0,
       CASE WHEN COALESCE(p.status, 'draft') = 'active' THEN 'active' ELSE 'draft' END,
       now(),
       now()
FROM products p
WHERE NOT EXISTS (SELECT 1 FROM product_variants v WHERE v.product_id = p.id);

-- Ledger of stock changes. Append only: rows are never updated or deleted.
CREATE TABLE IF NOT EXISTS stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id BIGINT NOT NULL,
    order_id BIGINT,
    delta INTEGER NOT NULL,
    reason VARCHAR(16) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT stock_movements_variant_id_fkey FOREIGN KEY (variant_id)
        REFERENCES product_variants(id) ON DELETE RESTRICT,
    CONSTRAINT stock_movements_order_id_fkey FOREIGN KEY (order_id)
        REFERENCES orders(id) ON DELETE RESTRICT,
    CONSTRAINT stock_movements_reason_check CHECK (reason IN ('reserve', 'release', 'restock', 'adjust'))
);

CREATE INDEX IF NOT EXISTS idx_stock_movements_variant_id ON stock_movements(variant_id);
CREATE INDEX IF NOT EXISTS idx_stock_movements_order_id ON stock_movements(order_id);

CREATE OR REPLACE FUNCTION jelly_stock_movements_append_only()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
    RAISE EXCEPTION 'stock_movements is append only';
END;
$$;

DROP TRIGGER IF EXISTS stock_movements_append_only ON stock_movements;
CREATE TRIGGER stock_movements_append_only
BEFORE UPDATE OR DELETE ON stock_movements
FOR EACH ROW EXECUTE FUNCTION jelly_stock_movements_append_only();
