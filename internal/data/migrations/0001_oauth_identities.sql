CREATE TABLE IF NOT EXISTS oauth_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    provider TEXT COLLATE "C" NOT NULL,
    subject VARCHAR(255) COLLATE "C" NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    CONSTRAINT oauth_identities_user_id_fkey FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT oauth_identities_provider_check CHECK (provider IN ('google', 'github')),
    CONSTRAINT oauth_identities_subject_check CHECK (subject ~ '[^[:space:]]')
);

CREATE INDEX IF NOT EXISTS idx_oauth_identities_user_id ON oauth_identities(user_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_oauth_identities_active_provider_subject
    ON oauth_identities(provider, subject) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_oauth_identities_active_user_provider
    ON oauth_identities(user_id, provider) WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS oauth_identity_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identity_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    provider TEXT COLLATE "C" NOT NULL,
    action TEXT NOT NULL,
    old_state JSONB,
    new_state JSONB,
    actor_id BIGINT,
    actor_email TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT oauth_identity_audit_log_actor_id_fkey FOREIGN KEY (actor_id)
        REFERENCES users(id) ON DELETE SET NULL ON UPDATE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_oauth_identity_audit_log_created_at ON oauth_identity_audit_log(created_at);
CREATE INDEX IF NOT EXISTS idx_oauth_identity_audit_log_actor_id ON oauth_identity_audit_log(actor_id);

CREATE OR REPLACE FUNCTION jelly_oauth_identity_set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
    NEW.updated_at := clock_timestamp();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS oauth_identities_set_updated_at ON oauth_identities;
CREATE TRIGGER oauth_identities_set_updated_at
BEFORE UPDATE ON oauth_identities
FOR EACH ROW EXECUTE FUNCTION jelly_oauth_identity_set_updated_at();

CREATE OR REPLACE FUNCTION jelly_oauth_identity_audit_change()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
DECLARE
    v_actor_id BIGINT;
    v_actor_email TEXT;
    v_old JSONB;
    v_new JSONB;
BEGIN
    v_actor_id := NULLIF(current_setting('jelly.actor_id', true), '')::BIGINT;
    IF v_actor_id IS NOT NULL THEN
        SELECT email INTO v_actor_email FROM public.users WHERE id = v_actor_id;
    END IF;

    IF TG_OP = 'UPDATE' OR TG_OP = 'DELETE' THEN
        v_old := jsonb_build_object(
            'id', OLD.id,
            'user_id', OLD.user_id,
            'provider', OLD.provider,
            'deleted_at', OLD.deleted_at
        );
    END IF;
    IF TG_OP = 'INSERT' OR TG_OP = 'UPDATE' THEN
        v_new := jsonb_build_object(
            'id', NEW.id,
            'user_id', NEW.user_id,
            'provider', NEW.provider,
            'deleted_at', NEW.deleted_at
        );
    END IF;

    INSERT INTO public.oauth_identity_audit_log
        (identity_id, user_id, provider, action, old_state, new_state, actor_id, actor_email)
    VALUES
        (CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END,
         CASE WHEN TG_OP = 'DELETE' THEN OLD.user_id ELSE NEW.user_id END,
         CASE WHEN TG_OP = 'DELETE' THEN OLD.provider ELSE NEW.provider END,
         TG_OP, v_old, v_new, v_actor_id, v_actor_email);

    DELETE FROM public.oauth_identity_audit_log
    WHERE created_at < now() - interval '90 days';

    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

DROP TRIGGER IF EXISTS oauth_identities_audit_change ON oauth_identities;
CREATE TRIGGER oauth_identities_audit_change
AFTER INSERT OR UPDATE OR DELETE ON oauth_identities
FOR EACH ROW EXECUTE FUNCTION jelly_oauth_identity_audit_change();

ALTER TABLE oauth_identities ENABLE ROW LEVEL SECURITY;
ALTER TABLE oauth_identity_audit_log ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE oauth_identities FROM PUBLIC;
REVOKE ALL ON TABLE oauth_identity_audit_log FROM PUBLIC;
