CREATE TABLE IF NOT EXISTS agents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    permissions TEXT[] NOT NULL DEFAULT '{}'::TEXT[],
    owner_id BIGINT,
    created_by BIGINT,
    status VARCHAR(16) NOT NULL DEFAULT 'active',
    disabled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    CONSTRAINT agents_owner_id_fkey FOREIGN KEY (owner_id)
        REFERENCES users(id) ON DELETE SET NULL ON UPDATE RESTRICT,
    CONSTRAINT agents_created_by_fkey FOREIGN KEY (created_by)
        REFERENCES users(id) ON DELETE SET NULL ON UPDATE RESTRICT,
    CONSTRAINT agents_status_check CHECK (status IN ('active', 'disabled')),
    CONSTRAINT agents_permissions_check CHECK (
        permissions <@ ARRAY[
            'posts.read', 'posts.write', 'pages.read', 'pages.write',
            'media.read', 'media.write', 'products.read', 'products.write',
            'orders.read', 'themes.read', 'themes.write', 'plugins.read',
            'plugins.write', 'settings.read', 'settings.write', 'logs.read'
        ]::TEXT[]
        AND array_position(permissions, NULL) IS NULL
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_agents_active_lower_name
    ON agents (lower(name)) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_agents_owner_id ON agents(owner_id);
CREATE INDEX IF NOT EXISTS idx_agents_created_by ON agents(created_by);

CREATE TABLE IF NOT EXISTS agent_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id BIGINT NOT NULL,
    key_hash CHAR(64) NOT NULL,
    prefix VARCHAR(12) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by BIGINT,
    last_used_at TIMESTAMPTZ,
    last_used_ip_masked VARCHAR(64) NOT NULL DEFAULT '',
    expires_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    revoked_by BIGINT,
    CONSTRAINT agent_keys_agent_id_fkey FOREIGN KEY (agent_id)
        REFERENCES agents(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT agent_keys_created_by_fkey FOREIGN KEY (created_by)
        REFERENCES users(id) ON DELETE SET NULL ON UPDATE RESTRICT,
    CONSTRAINT agent_keys_revoked_by_fkey FOREIGN KEY (revoked_by)
        REFERENCES users(id) ON DELETE SET NULL ON UPDATE RESTRICT,
    CONSTRAINT agent_keys_hash_check CHECK (key_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT agent_keys_prefix_check CHECK (prefix ~ '^jla_[A-Za-z0-9_-]{8}$'),
    CONSTRAINT agent_keys_hash_key UNIQUE (key_hash)
);

CREATE INDEX IF NOT EXISTS idx_agent_keys_agent_id ON agent_keys(agent_id);
CREATE INDEX IF NOT EXISTS idx_agent_keys_created_by ON agent_keys(created_by);
CREATE INDEX IF NOT EXISTS idx_agent_keys_revoked_by ON agent_keys(revoked_by);

CREATE TABLE IF NOT EXISTS agent_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at TIMESTAMPTZ NOT NULL DEFAULT now(),
    actor_type VARCHAR(8) NOT NULL,
    actor_user_id BIGINT,
    agent_id BIGINT NOT NULL,
    agent_name VARCHAR(80) NOT NULL,
    key_id BIGINT,
    key_prefix VARCHAR(12) NOT NULL DEFAULT '',
    action VARCHAR(32) NOT NULL,
    module VARCHAR(16) NOT NULL,
    method VARCHAR(8) NOT NULL DEFAULT '',
    route VARCHAR(255) NOT NULL DEFAULT '',
    status INTEGER NOT NULL DEFAULT 0,
    ip_masked VARCHAR(64) NOT NULL DEFAULT '',
    summary JSONB NOT NULL DEFAULT '{}'::JSONB,
    request_id VARCHAR(64) NOT NULL DEFAULT '',
    CONSTRAINT agent_events_actor_type_check CHECK (actor_type IN ('user', 'agent')),
    CONSTRAINT agent_events_actor_user_id_fkey FOREIGN KEY (actor_user_id)
        REFERENCES users(id) ON DELETE SET NULL ON UPDATE RESTRICT,
    CONSTRAINT agent_events_agent_id_fkey FOREIGN KEY (agent_id)
        REFERENCES agents(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT agent_events_summary_size_check CHECK (octet_length(summary::TEXT) <= 2048)
);

CREATE INDEX IF NOT EXISTS idx_agent_events_agent_id_id ON agent_events(agent_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_agent_events_at ON agent_events(at DESC);
CREATE INDEX IF NOT EXISTS idx_agent_events_actor_user_id ON agent_events(actor_user_id);

CREATE OR REPLACE FUNCTION jelly_agent_set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
    NEW.updated_at := clock_timestamp();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS agents_set_updated_at ON agents;
CREATE TRIGGER agents_set_updated_at
BEFORE UPDATE ON agents
FOR EACH ROW EXECUTE FUNCTION jelly_agent_set_updated_at();

ALTER TABLE agents ENABLE ROW LEVEL SECURITY;
ALTER TABLE agent_keys ENABLE ROW LEVEL SECURITY;
