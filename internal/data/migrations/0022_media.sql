CREATE TABLE IF NOT EXISTS media_policies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(64) NOT NULL CHECK (char_length(name) > 0),
    driver VARCHAR(80) NOT NULL CHECK (driver IN ('local', 's3') OR driver LIKE 'plugin:%'),
    purpose VARCHAR(16) NOT NULL DEFAULT 'media' CHECK (purpose IN ('media', 'backup')),
    config JSONB NOT NULL DEFAULT '{}'::jsonb,
    secret_enc BYTEA,
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_media_policies_default_per_purpose
    ON media_policies (purpose) WHERE is_default AND deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS media_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(128) NOT NULL CHECK (char_length(name) > 0),
    description TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT media_groups_name_key UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS media_files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id BIGINT NOT NULL REFERENCES media_policies(id) ON DELETE RESTRICT,
    group_id BIGINT REFERENCES media_groups(id) ON DELETE SET NULL,
    owner_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    path VARCHAR(512) NOT NULL CHECK (char_length(path) > 0),
    filename VARCHAR(255) NOT NULL,
    mime VARCHAR(127) NOT NULL DEFAULT 'application/octet-stream',
    size BIGINT NOT NULL DEFAULT 0 CHECK (size >= 0),
    width INTEGER,
    height INTEGER,
    alt TEXT NOT NULL DEFAULT '',
    sha256 VARCHAR(64) NOT NULL DEFAULT '',
    source VARCHAR(16) NOT NULL DEFAULT 'upload' CHECK (source IN ('upload', 'fetch', 'import', 'legacy')),
    original_of_id BIGINT REFERENCES media_files(id) ON DELETE SET NULL,
    variants JSONB NOT NULL DEFAULT '{}'::jsonb,
    exif_stripped BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT media_files_policy_path_key UNIQUE (policy_id, path)
);

CREATE INDEX IF NOT EXISTS idx_media_files_group_id ON media_files (group_id);
CREATE INDEX IF NOT EXISTS idx_media_files_sha256 ON media_files (sha256);

CREATE TABLE IF NOT EXISTS media_refs (
    file_id BIGINT NOT NULL REFERENCES media_files(id) ON DELETE CASCADE,
    ref_type VARCHAR(32) NOT NULL,
    ref_id BIGINT NOT NULL,
    PRIMARY KEY (file_id, ref_type, ref_id)
);
