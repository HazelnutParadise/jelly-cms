-- Ticket 07 (shop): coupons, their targets, batches and redemptions.
-- Idempotent: every statement can run again on a migrated database.

CREATE TABLE IF NOT EXISTS coupon_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prefix VARCHAR(20) NOT NULL DEFAULT '',
    size INTEGER NOT NULL DEFAULT 0,
    template JSONB,
    created_by_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT coupon_batches_created_by_id_fkey FOREIGN KEY (created_by_id)
        REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT coupon_batches_size_check CHECK (size >= 0)
);

CREATE TABLE IF NOT EXISTS coupons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL,
    label VARCHAR(120) NOT NULL DEFAULT '',
    kind VARCHAR(16) NOT NULL,
    value BIGINT NOT NULL DEFAULT 0,
    buy_qty INTEGER NOT NULL DEFAULT 0,
    get_qty INTEGER NOT NULL DEFAULT 0,
    min_subtotal BIGINT NOT NULL DEFAULT 0,
    scope VARCHAR(16) NOT NULL DEFAULT 'all',
    usage_limit INTEGER,
    used_count INTEGER NOT NULL DEFAULT 0,
    per_user_limit INTEGER,
    starts_at TIMESTAMPTZ,
    ends_at TIMESTAMPTZ,
    stackable_with_free_shipping BOOLEAN NOT NULL DEFAULT FALSE,
    members_only BOOLEAN NOT NULL DEFAULT FALSE,
    batch_id BIGINT,
    bound_email VARCHAR(255) NOT NULL DEFAULT '',
    status VARCHAR(16) NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT coupons_batch_id_fkey FOREIGN KEY (batch_id)
        REFERENCES coupon_batches(id) ON DELETE SET NULL,
    CONSTRAINT coupons_kind_check CHECK (kind IN ('percent', 'fixed', 'free_shipping', 'bogo')),
    CONSTRAINT coupons_scope_check CHECK (scope IN ('all', 'category', 'product')),
    CONSTRAINT coupons_status_check CHECK (status IN ('active', 'disabled')),
    CONSTRAINT coupons_value_check CHECK (value >= 0 AND (kind <> 'percent' OR value <= 100)),
    CONSTRAINT coupons_used_count_check CHECK (used_count >= 0),
    CONSTRAINT coupons_usage_limit_check CHECK (usage_limit IS NULL OR usage_limit >= 0),
    CONSTRAINT coupons_per_user_limit_check CHECK (per_user_limit IS NULL OR per_user_limit >= 0)
);

-- Codes are matched case-insensitively.
CREATE UNIQUE INDEX IF NOT EXISTS idx_coupons_code_lower ON coupons (lower(code));
CREATE INDEX IF NOT EXISTS idx_coupons_batch_id ON coupons(batch_id);

CREATE TABLE IF NOT EXISTS coupon_targets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_id BIGINT NOT NULL,
    target_type VARCHAR(16) NOT NULL,
    target_id BIGINT NOT NULL,
    CONSTRAINT coupon_targets_coupon_id_fkey FOREIGN KEY (coupon_id)
        REFERENCES coupons(id) ON DELETE CASCADE,
    CONSTRAINT coupon_targets_type_check CHECK (target_type IN ('category', 'product'))
);

-- target_id points at product_categories or products depending on target_type, so it has no foreign key.
CREATE UNIQUE INDEX IF NOT EXISTS idx_coupon_targets_unique ON coupon_targets(coupon_id, target_type, target_id);

CREATE TABLE IF NOT EXISTS coupon_redemptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_id BIGINT NOT NULL,
    order_id BIGINT NOT NULL,
    user_id BIGINT,
    email VARCHAR(255) NOT NULL DEFAULT '',
    released_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT coupon_redemptions_coupon_id_fkey FOREIGN KEY (coupon_id)
        REFERENCES coupons(id) ON DELETE RESTRICT,
    CONSTRAINT coupon_redemptions_order_id_fkey FOREIGN KEY (order_id)
        REFERENCES orders(id) ON DELETE CASCADE,
    CONSTRAINT coupon_redemptions_user_id_fkey FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE SET NULL
);

-- One redemption per coupon and order; ReleaseRedemption only sets released_at.
CREATE UNIQUE INDEX IF NOT EXISTS idx_coupon_redemptions_coupon_order ON coupon_redemptions(coupon_id, order_id);
CREATE INDEX IF NOT EXISTS idx_coupon_redemptions_coupon_email ON coupon_redemptions(coupon_id, email);

-- Orders reference the coupon they used; the column was added with the order columns in 0010.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'orders_coupon_id_fkey') THEN
        ALTER TABLE orders ADD CONSTRAINT orders_coupon_id_fkey FOREIGN KEY (coupon_id)
            REFERENCES coupons(id) ON DELETE SET NULL;
    END IF;
END
$$;
