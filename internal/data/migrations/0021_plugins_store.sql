CREATE TABLE IF NOT EXISTS plugins (
    id VARCHAR(64) PRIMARY KEY CHECK (id ~ '^[A-Za-z0-9][A-Za-z0-9._-]*$'),
    kind VARCHAR(32) NOT NULL DEFAULT 'plugin',
    version VARCHAR(64) NOT NULL DEFAULT '',
    source VARCHAR(16) NOT NULL DEFAULT 'upload' CHECK (source IN ('official', 'upload', 'url', 'bundled')),
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    signature VARCHAR(16) NOT NULL DEFAULT 'unsigned' CHECK (signature IN ('official', 'unsigned')),
    permissions_granted_hash VARCHAR(64) NOT NULL DEFAULT '',
    previous_version VARCHAR(64),
    installed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS plugin_settings (
    -- No foreign key: settings, snapshots and data outlive the plugins row so an
    -- uninstall can keep them (keep_settings=true) and a reinstall finds them again.
    plugin_id VARCHAR(64) PRIMARY KEY,
    "values" JSONB NOT NULL DEFAULT '{}'::jsonb,
    secrets_enc BYTEA,
    version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS plugin_setting_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plugin_id VARCHAR(64) NOT NULL,
    version INTEGER NOT NULL CHECK (version > 0),
    "values" JSONB NOT NULL DEFAULT '{}'::jsonb,
    secrets_enc BYTEA,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT plugin_setting_snapshots_plugin_version_key UNIQUE (plugin_id, version)
);

CREATE TABLE IF NOT EXISTS plugin_data (
    plugin_id VARCHAR(64) NOT NULL,
    collection VARCHAR(64) NOT NULL,
    key VARCHAR(255) NOT NULL,
    value JSONB NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (plugin_id, collection, key)
);

CREATE TABLE IF NOT EXISTS extension_bindings (
    point VARCHAR(64) NOT NULL,
    provider_id VARCHAR(128) NOT NULL,
    position INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (point, provider_id)
);

CREATE TABLE IF NOT EXISTS store_catalog (
    id VARCHAR(128) PRIMARY KEY,
    kind VARCHAR(32) NOT NULL DEFAULT 'plugin',
    name VARCHAR(255) NOT NULL DEFAULT '',
    version VARCHAR(64) NOT NULL DEFAULT '',
    category VARCHAR(64) NOT NULL DEFAULT '',
    description TEXT NOT NULL DEFAULT '',
    source VARCHAR(32) NOT NULL DEFAULT 'official',
    signature VARCHAR(16) NOT NULL DEFAULT 'unsigned' CHECK (signature IN ('official', 'unsigned')),
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    fetched_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS store_meta (
    key VARCHAR(64) PRIMARY KEY,
    value TEXT NOT NULL DEFAULT ''
);
