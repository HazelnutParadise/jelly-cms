-- Ticket 07 (shop): member addresses, invoice profiles and invoice records.
-- Idempotent: every statement can run again on a migrated database.
-- invoices is created now but not used yet (electronic invoices come later).

CREATE TABLE IF NOT EXISTS addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    label VARCHAR(60) NOT NULL DEFAULT '',
    recipient VARCHAR(120) NOT NULL DEFAULT '',
    phone VARCHAR(40) NOT NULL DEFAULT '',
    postcode VARCHAR(10) NOT NULL DEFAULT '',
    city VARCHAR(60) NOT NULL DEFAULT '',
    address VARCHAR(255) NOT NULL DEFAULT '',
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT addresses_user_id_fkey FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_addresses_user_id ON addresses(user_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_addresses_one_default ON addresses(user_id) WHERE is_default;

CREATE TABLE IF NOT EXISTS invoice_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    kind VARCHAR(16) NOT NULL DEFAULT 'none',
    carrier_code VARCHAR(16) NOT NULL DEFAULT '',
    tax_id VARCHAR(8) NOT NULL DEFAULT '',
    company_name VARCHAR(120) NOT NULL DEFAULT '',
    donation_code VARCHAR(16) NOT NULL DEFAULT '',
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT invoice_profiles_user_id_fkey FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT invoice_profiles_kind_check CHECK (kind IN ('none', 'personal_carrier', 'tax_id', 'donation'))
);

CREATE INDEX IF NOT EXISTS idx_invoice_profiles_user_id ON invoice_profiles(user_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_invoice_profiles_one_default ON invoice_profiles(user_id) WHERE is_default;

CREATE TABLE IF NOT EXISTS invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    kind VARCHAR(16) NOT NULL DEFAULT 'none',
    carrier_code VARCHAR(16) NOT NULL DEFAULT '',
    tax_id VARCHAR(8) NOT NULL DEFAULT '',
    company_name VARCHAR(120) NOT NULL DEFAULT '',
    donation_code VARCHAR(16) NOT NULL DEFAULT '',
    status VARCHAR(16) NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT invoices_order_id_fkey FOREIGN KEY (order_id)
        REFERENCES orders(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_invoices_order_id ON invoices(order_id);
