-- Ticket 07 (shop): low stock alert records. The table exists now; the feature comes later.
-- Idempotent: every statement can run again on a migrated database.

CREATE TABLE IF NOT EXISTS stock_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id BIGINT NOT NULL,
    stock INTEGER NOT NULL DEFAULT 0,
    threshold INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at TIMESTAMPTZ,
    CONSTRAINT stock_alerts_variant_id_fkey FOREIGN KEY (variant_id)
        REFERENCES product_variants(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_stock_alerts_variant_id ON stock_alerts(variant_id);
