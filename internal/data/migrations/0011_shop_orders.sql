-- Idempotent: every statement can run again on a migrated database.

-- Guest orders may exist without a user; the account is then set to NULL on user deletion.
ALTER TABLE orders ALTER COLUMN user_id DROP NOT NULL;

-- GORM creates fk_orders_user without an action. Replace it with ON DELETE SET NULL only when needed.
DO $$
DECLARE
    v_action "char";
BEGIN
    SELECT c.confdeltype INTO v_action
    FROM pg_constraint c
    WHERE c.conname = 'fk_orders_user' AND c.conrelid = 'orders'::regclass;
    IF v_action IS DISTINCT FROM 'n' THEN
        ALTER TABLE orders DROP CONSTRAINT IF EXISTS fk_orders_user;
        ALTER TABLE orders ADD CONSTRAINT fk_orders_user FOREIGN KEY (user_id)
            REFERENCES users(id) ON DELETE SET NULL;
    END IF;
END
$$;

