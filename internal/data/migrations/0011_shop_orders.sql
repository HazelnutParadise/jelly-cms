DO $$
DECLARE
    v_action "char";
BEGIN
    SELECT c.confdeltype INTO v_action
    FROM pg_constraint c
    WHERE c.conname = 'fk_order_items_product' AND c.conrelid = 'order_items'::regclass;
    IF v_action IS DISTINCT FROM 'n' THEN
        ALTER TABLE order_items DROP CONSTRAINT IF EXISTS fk_order_items_product;
        ALTER TABLE order_items ADD CONSTRAINT fk_order_items_product FOREIGN KEY (product_id)
            REFERENCES products(id) ON DELETE SET NULL;
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS order_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    at TIMESTAMPTZ NOT NULL DEFAULT now(),
    actor_user_id BIGINT,
    kind VARCHAR(40) NOT NULL,
    from_status VARCHAR(20) NOT NULL DEFAULT '',
    to_status VARCHAR(20) NOT NULL DEFAULT '',
    message TEXT NOT NULL DEFAULT '',
    meta JSONB,
    CONSTRAINT order_events_order_id_fkey FOREIGN KEY (order_id)
        REFERENCES orders(id) ON DELETE CASCADE,
    CONSTRAINT order_events_actor_user_id_fkey FOREIGN KEY (actor_user_id)
        REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_order_events_order_id ON order_events(order_id);

-- Sequence per calendar year for JL-YYYY-NNNN, reset every year by using a new row.
CREATE TABLE IF NOT EXISTS order_counters (
    year INTEGER PRIMARY KEY,
    seq BIGINT NOT NULL DEFAULT 0
);
