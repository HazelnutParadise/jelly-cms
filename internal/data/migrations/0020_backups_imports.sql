CREATE TABLE IF NOT EXISTS backups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state VARCHAR(16) NOT NULL DEFAULT 'queued' CHECK (state IN ('queued', 'running', 'done', 'failed')),
    kind VARCHAR(16) NOT NULL DEFAULT 'manual' CHECK (kind IN ('manual', 'scheduled', 'pre_restore')),
    contents JSONB NOT NULL DEFAULT '[]'::jsonb,
    encrypted BOOLEAN NOT NULL DEFAULT TRUE,
    note TEXT NOT NULL DEFAULT '',
    file_path VARCHAR(512),
    size_bytes BIGINT NOT NULL DEFAULT 0 CHECK (size_bytes >= 0),
    sha256 VARCHAR(64),
    manifest JSONB,
    last_error TEXT,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_backups_created_at ON backups (created_at DESC);

CREATE TABLE IF NOT EXISTS import_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state VARCHAR(16) NOT NULL DEFAULT 'uploaded' CHECK (state IN ('uploaded', 'mapped', 'dry_run', 'running', 'done', 'failed', 'cancelled')),
    source_name VARCHAR(255) NOT NULL DEFAULT '',
    source_bytes BIGINT NOT NULL DEFAULT 0 CHECK (source_bytes >= 0),
    site_url VARCHAR(2048) NOT NULL DEFAULT '',
    mapping JSONB NOT NULL DEFAULT '{}'::jsonb,
    options JSONB NOT NULL DEFAULT '{}'::jsonb,
    stats JSONB NOT NULL DEFAULT '{}'::jsonb,
    last_error TEXT,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS import_map (
    job_id BIGINT NOT NULL REFERENCES import_jobs(id) ON DELETE CASCADE,
    wp_type VARCHAR(32) NOT NULL,
    wp_id BIGINT NOT NULL,
    local_type VARCHAR(32) NOT NULL DEFAULT '',
    local_id BIGINT,
    wp_url VARCHAR(2048) NOT NULL DEFAULT '',
    PRIMARY KEY (job_id, wp_type, wp_id)
);
