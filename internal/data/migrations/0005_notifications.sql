-- Notification center, preferences and the delivery queue
-- (docs/tickets/06-accounts.md, 資料表 notifications / notification_settings / notification_prefs / notification_deliveries).

CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind VARCHAR(64) NOT NULL,
    category VARCHAR(16) NOT NULL,
    title_key VARCHAR(120) NOT NULL DEFAULT '',
    params JSONB NOT NULL DEFAULT '{}'::jsonb,
    actions JSONB NOT NULL DEFAULT '[]'::jsonb,
    group_key VARCHAR(255) NOT NULL DEFAULT '',
    count INTEGER NOT NULL DEFAULT 1,
    read_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL DEFAULT (now() + interval '90 days'),
    CONSTRAINT notifications_category_check CHECK (category IN ('comments', 'orders', 'system', 'security'))
);

CREATE INDEX IF NOT EXISTS idx_notifications_user_created ON notifications(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_notifications_expires_at ON notifications(expires_at);
-- At most one unread row per group, so repeated events add to its count instead of stacking.
CREATE UNIQUE INDEX IF NOT EXISTS idx_notifications_unread_group
    ON notifications(user_id, group_key) WHERE read_at IS NULL AND group_key <> '';

CREATE TABLE IF NOT EXISTS notification_settings (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    webhook_url TEXT NOT NULL DEFAULT '',
    quiet_start VARCHAR(5) NOT NULL DEFAULT '',
    quiet_end VARCHAR(5) NOT NULL DEFAULT '',
    quiet_tz VARCHAR(64) NOT NULL DEFAULT ''
);

-- A missing row means the default: in-app on, email and webhook off.
CREATE TABLE IF NOT EXISTS notification_prefs (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    event VARCHAR(64) NOT NULL,
    in_app BOOLEAN NOT NULL DEFAULT TRUE,
    email BOOLEAN NOT NULL DEFAULT FALSE,
    webhook BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (user_id, event)
);

CREATE TABLE IF NOT EXISTS notification_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id BIGINT NOT NULL REFERENCES notifications(id) ON DELETE CASCADE,
    channel VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'pending',
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    error TEXT NOT NULL DEFAULT '',
    CONSTRAINT notification_deliveries_channel_check CHECK (channel IN ('email', 'webhook')),
    CONSTRAINT notification_deliveries_status_check CHECK (status IN ('pending', 'sent', 'failed', 'held'))
);

CREATE INDEX IF NOT EXISTS idx_notification_deliveries_queue
    ON notification_deliveries(status, next_attempt_at);
CREATE INDEX IF NOT EXISTS idx_notification_deliveries_notification_id
    ON notification_deliveries(notification_id);
