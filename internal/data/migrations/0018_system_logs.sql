CREATE TABLE IF NOT EXISTS system_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at TIMESTAMPTZ NOT NULL DEFAULT now(),
    level SMALLINT NOT NULL CHECK (level BETWEEN 0 AND 3),
    source VARCHAR(16) NOT NULL CHECK (source IN ('app', 'http', 'payment', 'plugin', 'audit', 'cron', 'job', 'crawler')),
    message TEXT NOT NULL,
    fields JSONB,
    request_id VARCHAR(32),
    actor_user_id BIGINT,
    plugin_id VARCHAR(64),
    ip_masked VARCHAR(64)
);

CREATE INDEX IF NOT EXISTS idx_system_logs_at ON system_logs (at DESC);
CREATE INDEX IF NOT EXISTS idx_system_logs_source_at ON system_logs (source, at);
CREATE INDEX IF NOT EXISTS idx_system_logs_level_at ON system_logs (level, at);
CREATE INDEX IF NOT EXISTS idx_system_logs_request_id ON system_logs (request_id);
