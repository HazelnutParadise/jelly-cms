package server

import (
	"github.com/HazelnutParadise/jelly-cms/internal/syslog"
	"github.com/labstack/echo/v4"
)

// Error envelope shared by the agent API (docs/tickets/14-agent-api.md, 錯誤格式)
// and the WebMCP work in issue #7:
//
//	{"code": "...", "message": "...", "details": {...}, "correlation_id": "req_..."}
//
// details is always an object; correlation_id equals the X-Request-ID response
// header. This file is the ticket 14 skeleton.

// writeAPIError writes the envelope with status. A nil details map is written
// as {}.
func writeAPIError(c echo.Context, status int, code, message string, details map[string]any) error {
	if details == nil {
		details = map[string]any{}
	}
	id := requestIDFor(c)
	return c.JSON(status, map[string]any{"code": code, "message": message, "details": details, "correlation_id": id})
}

// requestIDFor returns the ID generated by the shared server RequestID
// middleware. It falls back to the X-Request-ID response header when the
// middleware did not set a context value.
func requestIDFor(c echo.Context) string {
	if id, ok := c.Get(syslog.RequestIDContextKey).(string); ok && id != "" {
		return id
	}
	return c.Response().Header().Get(syslog.RequestIDHeader)
}
